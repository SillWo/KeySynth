#[cfg(test)]
mod tests {
    use super::*;

    const ALL_TEXT: &[Text] = &[
        Text::Subtitle,
        Text::Language,
        Text::KeySounds,
        Text::On,
        Text::Off,
        Text::Volume,
        Text::Transpose,
        Text::Waveform,
        Text::Mode,
        Text::Advanced,
        Text::Attack,
        Text::Release,
        Text::StartWithWindows,
        Text::MinimizeToTray,
        Text::AudioReady,
        Text::AudioUnavailable,
        Text::KeyboardUnavailable,
        Text::HotkeyUnavailable,
        Text::SaveError,
        Text::AutostartError,
        Text::Open,
        Text::EnableSounds,
        Text::DisableSounds,
        Text::Exit,
        Text::Ms,
        Text::Sine,
        Text::Triangle,
        Text::Sawtooth,
        Text::Square,
        Text::WickiHayden,
        Text::Chromatic,
        Text::Random,
        Text::ControlsError,
        Text::ModuleError,
        Text::WindowClassError,
        Text::WindowCreateError,
    ];

    #[test]
    fn every_text_has_both_translations() {
        for &id in ALL_TEXT {
            assert!(
                !text(AppLanguage::English, id).trim().is_empty(),
                "empty English text: {id:?}"
            );
            assert!(
                !text(AppLanguage::Russian, id).trim().is_empty(),
                "empty Russian text: {id:?}"
            );
        }
    }
}
